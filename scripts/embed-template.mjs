// Embeds templates/QA_Course_Coverage_Report.xlsx into lib/qaTemplate.ts so the export works on Vercel
// without reading files at runtime.  Run after replacing the template:  node scripts/embed-template.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const src = path.join(root, 'templates', 'QA_Course_Coverage_Report.xlsx');
const out = path.join(root, 'lib', 'qaTemplate.ts');
const b64 = fs.readFileSync(src).toString('base64');
fs.writeFileSync(
  out,
  `// Generated by scripts/embed-template.mjs from templates/QA_Course_Coverage_Report.xlsx — do not edit by hand.\n` +
    `export const QA_TEMPLATE_BASE64 =\n  '${b64}';\n`,
);
console.log(`Wrote ${out} (${Math.round(b64.length / 1024)} KB)`);
